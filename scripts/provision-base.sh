wait_for_t3

# Providers without snapshots: install the configured runtimes now that T3 is up (not fatal)
if [ "$BAKE_CLEAN" != "1" ] && { [ -n "${T3_PREPARE_ACP_AGENTS:-}" ] || [ -n "${T3_INSTALL_PROVIDERS:-}" ]; }; then
  setup_token="$(timeout 30 "$t3" auth session issue --token-only --ttl 1h --label boot-provider-setup 2>/dev/null || true)"
  if [ -z "$setup_token" ]; then
    echo "[provision] could not issue a token for provider runtime setup; skipping" >&2
  elif ! run_provider_setup "$setup_token" >&2; then
    echo "[provision] provider runtime setup failed (continuing without it)" >&2
  fi
  unset setup_token
fi

# Optionally register project via official `t3 project add` CLI (fallback handled by sentinel if unavailable)
if [ -n "${PROJECT_WORKDIR:-}" ] && [ -n "${PROJECT_TITLE:-}" ]; then
  "$t3" project add "$PROJECT_WORKDIR" --title "$PROJECT_TITLE" >/dev/null 2>&1 || true
